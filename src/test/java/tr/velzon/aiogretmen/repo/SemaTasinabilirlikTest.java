package tr.velzon.aiogretmen.repo;

import org.junit.jupiter.api.Test;
import org.springframework.core.io.ClassPathResource;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.jdbc.datasource.init.ScriptUtils;

import java.nio.charset.StandardCharsets;
import java.sql.Connection;
import java.util.regex.Pattern;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

/**
 * Faz 9d (ADR-0014 §3): {@code schema.sql} H2 VE PostgreSQL'de çalışan TEK dosyadır. PostgreSQL'e her
 * {@code verify}'da bağlanamadığımız için (Testcontainers yok) H2'ye özgü sözdizimi burada metinden
 * yakalanır; gerçek PostgreSQL koşusu {@code SitePostgresEntegrasyonTest} (opt-in).
 */
class SemaTasinabilirlikTest {

    private static String semaKodu() throws Exception {
        String ham = new ClassPathResource("schema.sql").getContentAsString(StandardCharsets.UTF_8);
        return ham.replaceAll("--[^\\n]*", "").toUpperCase();   // yorumlar kurallara takılmasın
    }

    @Test
    void h2yeOzguSozdizimiYok() throws Exception {
        String sql = semaKodu();
        assertThat(sql).as("IDENTITY tipi PostgreSQL'de yok → BIGINT GENERATED BY DEFAULT AS IDENTITY")
                .doesNotContainPattern(Pattern.compile("\\bID\\s+IDENTITY\\b"));
        assertThat(sql).as("CLOB PostgreSQL'de yok → TEXT").doesNotContainPattern(Pattern.compile("\\bCLOB\\b"));
        assertThat(sql).as("PostgreSQL ADD CONSTRAINT IF NOT EXISTS desteklemez")
                .doesNotContainPattern(Pattern.compile("ADD\\s+CONSTRAINT\\s+IF\\s+NOT\\s+EXISTS"));
        assertThat(sql).as("H2 MERGE ... KEY / DATEADD / AUTO_INCREMENT taşınabilir değil")
                .doesNotContainPattern(Pattern.compile("\\bMERGE\\s+INTO\\b|\\bDATEADD\\b|\\bAUTO_INCREMENT\\b"));
        assertThat(sql).as("her CREATE idempotent olmalı")
                .doesNotContainPattern(Pattern.compile("CREATE\\s+(UNIQUE\\s+)?(TABLE|INDEX)\\s+(?!IF\\s+NOT\\s+EXISTS)"));
    }

    @Test
    void yeniH2KurulumundaIkiKezCalisirVeKullaniciyaBolunmusBenzersizlikVar() throws Exception {
        var ds = new DriverManagerDataSource("jdbc:h2:mem:sematasinabilir;DB_CLOSE_DELAY=-1", "sa", "");
        try (Connection c = ds.getConnection()) {
            ScriptUtils.executeSqlScript(c, new ClassPathResource("schema.sql"));
            ScriptUtils.executeSqlScript(c, new ClassPathResource("schema.sql"));
        }
        JdbcTemplate jdbc = new JdbcTemplate(ds);
        jdbc.update("INSERT INTO gorev_ilerleme (kullanici_id, hafta, gun, gorev_index) VALUES ('a',1,1,0)");
        jdbc.update("INSERT INTO gorev_ilerleme (kullanici_id, hafta, gun, gorev_index) VALUES ('b',1,1,0)");
        assertThatThrownBy(() -> jdbc.update(
                "INSERT INTO gorev_ilerleme (kullanici_id, hafta, gun, gorev_index) VALUES ('a',1,1,0)"))
                .isInstanceOf(DuplicateKeyException.class);
        // TEXT kolonu uzun metni tutar (H2'de CLOB eş adı)
        String uzun = "x".repeat(100_000);
        jdbc.update("INSERT INTO gonderim (hafta, tur, icerik) VALUES (1, 'OZET', ?)", uzun);
        assertThat(jdbc.queryForObject("SELECT icerik FROM gonderim", String.class)).hasSize(100_000);
    }

    @Test
    void adr0008OncesiH2DosyasiGocEder() throws Exception {
        // ADR-0008 öncesi: kullanici_id yok, benzersizlik kullanıcısız (H2 otomatik adı CONSTRAINT_BB)
        var ds = new DriverManagerDataSource("jdbc:h2:mem:semaeski;DB_CLOSE_DELAY=-1", "sa", "");
        JdbcTemplate jdbc = new JdbcTemplate(ds);
        jdbc.execute("""
                CREATE TABLE gorev_ilerleme (id IDENTITY PRIMARY KEY, hafta INT NOT NULL, gun INT NOT NULL,
                  gorev_index INT NOT NULL, tamamlandi BOOLEAN NOT NULL DEFAULT FALSE,
                  tarih TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                  CONSTRAINT CONSTRAINT_BB UNIQUE (hafta, gun, gorev_index))""");
        jdbc.update("INSERT INTO gorev_ilerleme (hafta, gun, gorev_index, tamamlandi) VALUES (1,1,0,TRUE)");

        try (Connection c = ds.getConnection()) {
            ScriptUtils.executeSqlScript(c, new ClassPathResource("schema.sql"));
            ScriptUtils.executeSqlScript(c, new ClassPathResource("schema.sql"));
        }

        assertThat(jdbc.queryForObject("SELECT kullanici_id FROM gorev_ilerleme", String.class)).isEqualTo("yerel");
        jdbc.update("INSERT INTO gorev_ilerleme (kullanici_id, hafta, gun, gorev_index) VALUES ('a',1,1,0)");
        assertThatThrownBy(() -> jdbc.update(
                "INSERT INTO gorev_ilerleme (kullanici_id, hafta, gun, gorev_index) VALUES ('yerel',1,1,0)"))
                .isInstanceOf(DuplicateKeyException.class);
    }
}
